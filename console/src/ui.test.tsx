import { afterEach, expect, it } from 'vitest'
import { render, screen, fireEvent, cleanup } from '@testing-library/react'
import { MemoryRouter } from 'react-router-dom'
import { QueryClient, QueryClientProvider } from '@tanstack/react-query'
import { setupServer } from 'msw/node'
import { http, HttpResponse } from 'msw'
import App from './ui'

const server = setupServer(
  http.get('/meta/capabilities', () => HttpResponse.json({ version: '0.1.0', provider_mode: 'mock', providers: ['mock'], pricing: {}, dev_controls: false, streaming: false, real_providers: false, usage_history: false, config_mutation: false })),
  http.get('/admin/teams', () => HttpResponse.json({ teams: [{ team_id: 'team_alpha', name: 'Team Alpha', allowed_models: ['smart-chat'], rate_limits: { requests_per_minute: 60, tokens_per_minute: 50000 }, budgets: { daily_usd: 5, monthly_usd: 50 } }] })),
  http.get('/ready', () => HttpResponse.json({ status: 'ok', dependencies: { redis: 'ok' } })),
  http.get('/providers/health', () => HttpResponse.json({ providers: [] })),
  http.get('/admin/teams/team_alpha/usage', () => HttpResponse.json({ team_id: 'team_alpha', tokens_this_minute: 0, spend: { daily_usd: 0, monthly_usd: 0 } }))
)
server.listen()
afterEach(() => { cleanup(); server.resetHandlers() })

it('shows the live overview and navigates to the playground', async () => {
  render(<QueryClientProvider client={new QueryClient({ defaultOptions: { queries: { retry: false } } })}><MemoryRouter><App /></MemoryRouter></QueryClientProvider>)
  expect(await screen.findByRole('heading', { name: 'Gateway overview' })).toBeInTheDocument()
  expect(await screen.findByText('Simulated provider · responses are generated by MockProvider')).toBeInTheDocument()
  fireEvent.click(screen.getByRole('link', { name: 'Playground' }))
  expect(await screen.findByRole('heading', { name: 'Playground' })).toBeInTheDocument()
  expect(screen.getByText('Streaming: unavailable in this version')).toBeInTheDocument()
  expect(screen.queryByRole('link', { name: 'Test Lab' })).not.toBeInTheDocument()
})
