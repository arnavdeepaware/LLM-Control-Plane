import { afterEach, expect, it } from 'vitest'
import { render, screen, fireEvent, cleanup, waitFor } from '@testing-library/react'
import { MemoryRouter } from 'react-router-dom'
import { QueryClient, QueryClientProvider } from '@tanstack/react-query'
import { setupServer } from 'msw/node'
import { http, HttpResponse } from 'msw'
import App from './ui'

const server = setupServer(
  http.get('/admin/session', () => HttpResponse.json({ authenticated: true, expires_at: 4102444800 })),
  http.post('/admin/session', () => HttpResponse.json({ authenticated: true, expires_at: 4102444800 })),
  http.delete('/admin/session', () => HttpResponse.json({ authenticated: false })),
  http.get('/meta/capabilities', () => HttpResponse.json({ version: '0.1.0', provider_mode: 'mock', providers: ['mock'], pricing: {}, dev_controls: false, streaming: false, real_providers: false, usage_history: false, config_mutation: false })),
  http.get('/admin/teams', () => HttpResponse.json({ teams: [
    { team_id: 'team_alpha', name: 'Team Alpha', allowed_models: ['smart-chat'], rate_limits: { requests_per_minute: 60, tokens_per_minute: 50000 }, budgets: { daily_usd: 5, monthly_usd: 50 } },
    { team_id: 'team_beta', name: 'Team Beta', allowed_models: ['cheap-chat'], rate_limits: { requests_per_minute: 20, tokens_per_minute: 10000 }, budgets: { daily_usd: 1, monthly_usd: 20 } },
  ] })),
  http.get('/ready', () => HttpResponse.json({ status: 'ok', dependencies: { redis: 'ok' } })),
  http.get('/providers/health', () => HttpResponse.json({ providers: [] })),
  http.get('/admin/auth/summary', () => HttpResponse.json({ success_total: 0, failure_total: 0, success_rate: null })),
  http.get('/admin/teams/team_alpha/usage', () => HttpResponse.json({ team_id: 'team_alpha', tokens_this_minute: 0, spend: { daily_usd: 0, monthly_usd: 0 } })),
  http.get('/admin/teams/team_beta/usage', () => HttpResponse.json({ team_id: 'team_beta', tokens_this_minute: 0, spend: { daily_usd: 0, monthly_usd: 0 } })),
  http.get('/v1/me', () => HttpResponse.json({ team_id: 'team_alpha', name: 'Team Alpha', allowed_models: ['smart-chat'], rate_limits: { requests_per_minute: 60, tokens_per_minute: 50000 }, budgets: { daily_usd: 5, monthly_usd: 50 } }))
)
server.listen()
afterEach(() => { cleanup(); server.resetHandlers(); sessionStorage.clear() })

function renderApp() {
  return render(<QueryClientProvider client={new QueryClient({ defaultOptions: { queries: { retry: false } } })}><MemoryRouter><App /></MemoryRouter></QueryClientProvider>)
}

it('shows the live overview and navigates to the playground', async () => {
  renderApp()
  expect(await screen.findByRole('heading', { name: 'Gateway overview' })).toBeInTheDocument()
  expect(await screen.findByText('Simulated provider · responses are generated by MockProvider')).toBeInTheDocument()
  fireEvent.click(screen.getByRole('link', { name: 'Playground' }))
  expect(await screen.findByRole('heading', { name: 'Playground' })).toBeInTheDocument()
  expect(screen.getByText('Streaming: unavailable in this version')).toBeInTheDocument()
  expect(screen.queryByRole('button', { name: 'Use local sample key' })).not.toBeInTheDocument()
  expect(screen.queryByRole('link', { name: 'Test Lab' })).not.toBeInTheDocument()
})

it('gates protected console data behind an admin session', async () => {
  server.use(http.get('/admin/session', () => HttpResponse.json({ error: 'unauthorized', message: 'Admin session required' }, { status: 401 })))
  renderApp()
  expect(await screen.findByRole('heading', { name: 'Administrator access' })).toBeInTheDocument()
  fireEvent.change(screen.getByLabelText('Admin access code'), { target: { value: 'manual-admin-code' } })
  fireEvent.click(screen.getByRole('button', { name: 'Open developer console' }))
  expect(await screen.findByRole('heading', { name: 'Gateway overview' })).toBeInTheDocument()
})

it('verifies a team key, synchronizes identity, and clears it', async () => {
  server.use(http.get('/v1/me', () => HttpResponse.json({ team_id: 'team_beta', name: 'Team Beta', allowed_models: ['cheap-chat'], rate_limits: { requests_per_minute: 20, tokens_per_minute: 10000 }, budgets: { daily_usd: 1, monthly_usd: 20 } })))
  renderApp()
  fireEvent.click(await screen.findByRole('link', { name: 'Playground' }))
  await screen.findByRole('heading', { name: 'Playground' })
  fireEvent.change(screen.getByLabelText('Team API key'), { target: { value: 'beta-secret-key' } })
  fireEvent.click(screen.getByRole('button', { name: 'Verify key' }))
  expect(await screen.findByText(/Authenticated as Team Beta/)).toBeInTheDocument()
  expect((screen.getByLabelText('Team configuration') as HTMLSelectElement).value).toBe('team_beta')
  expect(sessionStorage.getItem('api-key')).toBe('beta-secret-key')
  fireEvent.click(screen.getByRole('button', { name: 'Clear API key / Switch team' }))
  expect(await screen.findByText(/Credential cleared/)).toBeInTheDocument()
  expect(sessionStorage.getItem('api-key')).toBeNull()
})

it('announces an invalid team credential and keeps chat disabled', async () => {
  server.use(http.get('/v1/me', () => HttpResponse.json({ error: 'unauthorized', message: 'Invalid API key' }, { status: 401 })))
  renderApp()
  fireEvent.click(await screen.findByRole('link', { name: 'Playground' }))
  await screen.findByRole('heading', { name: 'Playground' })
  fireEvent.change(screen.getByLabelText('Team API key'), { target: { value: 'wrong' } })
  fireEvent.click(screen.getByRole('button', { name: 'Verify key' }))
  expect(await screen.findByText(/Credential verification failed/)).toBeInTheDocument()
  await waitFor(() => expect(screen.getByRole('button', { name: 'Send request' })).toBeDisabled())
})

it('invalidates verified identity when chat returns 401', async () => {
  server.use(http.post('/v1/chat/completions', () => HttpResponse.json({ error: 'unauthorized', message: 'Invalid API key' }, { status: 401 })))
  renderApp()
  fireEvent.click(await screen.findByRole('link', { name: 'Playground' }))
  await screen.findByRole('heading', { name: 'Playground' })
  fireEvent.change(screen.getByLabelText('Team API key'), { target: { value: 'alpha-secret-key' } })
  fireEvent.click(screen.getByRole('button', { name: 'Verify key' }))
  await screen.findByText(/Authenticated as Team Alpha/)
  fireEvent.change(screen.getByLabelText('Message 1 content'), { target: { value: 'hello' } })
  fireEvent.click(screen.getByRole('button', { name: 'Send request' }))
  expect(await screen.findByText(/gateway rejected this credential/i)).toBeInTheDocument()
  expect(screen.getByRole('button', { name: 'Send request' })).toBeDisabled()
})

it('ends the admin session and returns to the access gate', async () => {
  renderApp()
  fireEvent.click(await screen.findByRole('button', { name: 'End admin session' }))
  expect(await screen.findByRole('heading', { name: 'Administrator access' })).toBeInTheDocument()
})
